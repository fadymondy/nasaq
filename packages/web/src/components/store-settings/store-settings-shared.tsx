/** What a save callback resolves. Resolve `{ error }` to keep the form open and show the message. */
export type SettingsResult = void | { error?: string };

export function Money({ minor, currency, className }: { minor: number; currency: string; className?: string }) {
  return <Num className={className} value={minorToMajor(minor, currency)} format={{ style: "currency", currency }} />;
}

/** "EG" to "Egypt" or "مصر", in the page language. Falls back to the code. */
export function regionName(locale: string, code: string): string {
  try {
    return new Intl.DisplayNames([locale], { type: "region" }).of(code.trim().toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

let counter = 0;
/** A short unique id for a new record. Replace it on your server. */
export const uid = (prefix: string) => `${prefix}-${Date.now().toString(36)}${(counter++).toString(36)}`;

/** Runs a save or delete, tracks busy and the error, and reports whether it worked. */
export function useAction(fallback: string) {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const alive = useRef(true);
  const run = useCallback(
    async (job: () => Promise<SettingsResult>): Promise<boolean> => {
      setBusy(true);
      setError(null);
      try {
        const r = await job();
        if (r && typeof r === "object" && r.error) {
          setError(r.error);
          return false;
        }
        return true;
      } catch (e) {
        setError(e instanceof Error && e.message ? e.message : fallback);
        return false;
      } finally {
        if (alive.current) setBusy(false);
      }
    },
    [fallback],
  );
  return { busy, error, setError, run };
}

/** "14" or "14.5" or "7.25" to basis points, with integer maths. Undefined when it is not a percentage of 0 to 100. */
export function percentToBps(text: string): number | undefined {
  const m = /^(\d{1,3})(?:[.,](\d{1,2}))?$/.exec(text.trim());
  if (!m) return undefined;
  const bps = Number(m[1]) * 100 + Number((m[2] ?? "").padEnd(2, "0") || 0);
  return bps <= 10000 ? bps : undefined;
}

/** Basis points as a percentage string without float error: 1450 gives "14.5". */
export const bpsToPercent = (bps: number): string => {
  const whole = Math.trunc(bps / 100);
  const frac = String(Math.abs(bps % 100)).padStart(2, "0").replace(/0+$/, "");
  return frac ? `${whole}.${frac}` : String(whole);
};
