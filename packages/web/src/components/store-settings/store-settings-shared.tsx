export const STORE_SETTINGS_STRINGS = { en, ar };

const NESTED = ["rateTypes", "tierIssues", "unavailable", "kinds", "classes", "standings", "rejections", "giftStatuses", "entryKinds", "giftErrors", "ledgerIssues"] as const;
type Nested = (typeof NESTED)[number];
/** Every text can be replaced. Nested groups (rate types, rejections and so on) merge key by key. */
export type StoreSettingsLabels = Partial<Omit<SettingsStrings, Nested>> & { [K in Nested]?: Partial<SettingsStrings[K]> };

export function useSettingsStrings(labels?: StoreSettingsLabels) {
  const locale = useOptionalNasaq()?.locale ?? "en";
  const base = STORE_SETTINGS_STRINGS[locale.startsWith("ar") ? "ar" : "en"];
  const t = { ...base, ...labels } as SettingsStrings;
  for (const k of NESTED) (t as Record<string, unknown>)[k] = { ...base[k], ...labels?.[k] };
  return { t, locale, n: (v: number) => formatNumber(v, locale) };
}

