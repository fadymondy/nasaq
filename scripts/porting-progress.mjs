// Writes docs/porting-progress.md from the files on disk: which React components have a Vue port
// (packages/vue/src/components/<name>) and a Blade port (packages/php/resources/views/components/<name>),
// in dependency order. Ports never edit the list by hand, so parallel ports cannot conflict.
// Stacks that cannot have a component are listed in docs/porting-na.json: { "<name>": { "vue"?: "reason", "blade"?: "reason" } }.
//
//   node scripts/porting-progress.mjs
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/(\w:)/, "$1");
const web = join(root, "packages/web/src/components");
const names = readdirSync(web).filter((n) => statSync(join(web, n)).isDirectory());
const na = existsSync(join(root, "docs/porting-na.json")) ? JSON.parse(readFileSync(join(root, "docs/porting-na.json"), "utf8")) : {};

const deps = {};
const libs = {};
for (const n of names) {
  const d = new Set();
  const l = new Set();
  for (const f of readdirSync(join(web, n))) {
    if (!/\.tsx?$/.test(f) || /\.test\./.test(f)) continue;
    const src = readFileSync(join(web, n, f), "utf8");
    for (const m of src.matchAll(/from "\.\.\/([\w-]+)/g)) if (m[1] !== n && names.includes(m[1])) d.add(m[1]);
    for (const m of src.matchAll(/from "(recharts|@tiptap[^"]*|@xyflow[^"]*|shiki[^"]*|@dnd-kit[^"]*|sonner|cmdk|react-day-picker|embla[^"]*|vaul|input-otp|react-resizable-panels)"/g))
      l.add(m[1].split("/").slice(0, 2).join("/"));
  }
  deps[n] = [...d];
  libs[n] = [...l];
}

const level = {};
const depth = (n, seen = new Set()) => {
  if (n in level) return level[n];
  if (seen.has(n)) return 0;
  seen.add(n);
  return (level[n] = Math.max(0, ...deps[n].map((d) => depth(d, seen) + 1)));
};
names.forEach((n) => depth(n));

const has = {
  vue: (n) => existsSync(join(root, "packages/vue/src/components", n, "index.ts")),
  blade: (n) => existsSync(join(root, "packages/php/resources/views/components", n)),
};
const box = (n, stack) => (na[n]?.[stack] ? "[-]" : has[stack](n) ? "[x]" : "[ ]");
const done = names.filter((n) => (has.vue(n) || na[n]?.vue) && (has.blade(n) || na[n]?.blade));

const out = [
  "# Porting progress",
  "",
  "Generated by `node scripts/porting-progress.mjs` from the files on disk; do not edit. Order: dependency level (a component imports only components from lower levels), then name. `[x]` ported, `[-]` not applicable (docs/porting-na.json). How to port: [PORTING.md](PORTING.md).",
  "",
  `**${done.length} of ${names.length} complete** · Vue ${names.filter(has.vue).length} · Blade ${names.filter(has.blade).length}`,
  "",
];
for (const l of [...new Set(Object.values(level))].sort((a, b) => a - b)) {
  out.push(`## Level ${l}`, "");
  for (const n of names.filter((x) => level[x] === l).sort()) {
    const notes = Object.entries(na[n] ?? {}).map(([s, r]) => `${s} n/a: ${r}`);
    out.push(
      `- ${box(n, "vue")} vue ${box(n, "blade")} blade · **${n}**` +
        (deps[n].length ? ` · imports ${deps[n].join(", ")}` : "") +
        (libs[n].length ? ` · libs ${libs[n].join(", ")}` : "") +
        (notes.length ? ` · ${notes.join("; ")}` : ""),
    );
  }
  out.push("");
}
writeFileSync(join(root, "docs/porting-progress.md"), out.join("\n"));
console.log(`${done.length}/${names.length} complete`);
